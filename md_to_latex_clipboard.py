from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
import argparse
import re
import sys


# "auto":
#   Latex Type: Chapter -> chapter mode
#   Latex Type: Section -> section mode
#
# "section":
#   note title -> \section
#   ##         -> \subsection
#   ###        -> \subsubsection
#
# "chapter":
#   note title -> \chapter
#   ##         -> \section
#   ###        -> \subsection
# "article":
#   no wrapper heading
#   ##         -> \section
#   ###        -> \subsection
DOCUMENT_LEVEL = "auto"


@dataclass
class ConversionState:
    warnings_enabled: bool = True
    labels: dict[str, str] = field(default_factory=dict)
    warning_count: int = 0

    def warn(self, message: str) -> None:
        self.warning_count += 1
        if self.warnings_enabled:
            print(f"WARNING: {message}", file=sys.stderr)

    def register_label(self, label: str, source: str) -> None:
        if label in self.labels:
            self.warn(
                f"duplicate label '{label}' generated by {source}; "
                f"already generated by {self.labels[label]}"
            )
        else:
            self.labels[label] = source


@dataclass
class CaptionParts:
    short_latex: str
    long_latex: str
    label_source: str


@dataclass
class NoteInfo:
    title: str
    path: Path
    latex_type: str
    latex_parent: str | None
    prefix: str
    note_label: str
    heading_label: str
    headings: dict[str, tuple[str, str]] = field(default_factory=dict)
    equation_tags: set[str] = field(default_factory=set)
    figure_tags: set[str] = field(default_factory=set)
    table_tags: set[str] = field(default_factory=set)


def canonical_prop_key(key: str) -> str:
    return re.sub(r"[\s_\-]+", "", key.strip()).lower()


def clean_yaml_scalar(value: str) -> str:
    value = value.strip()

    if value.startswith(("'", '"')) and value.endswith(("'", '"')):
        value = value[1:-1].strip()

    return value


def normalize_note_reference(value: str) -> str:
    value = clean_yaml_scalar(value)

    if value.startswith("[[") and value.endswith("]]"):
        value = value[2:-2]
        value = value.split("|", 1)[0]
        value = value.split("#", 1)[0]

    return value.strip()


def get_prop(props: dict[str, str], name: str, default: str = "") -> str:
    target = canonical_prop_key(name)

    for key, value in props.items():
        if canonical_prop_key(key) == target:
            return value

    return default


def parse_frontmatter(markdown: str) -> tuple[dict[str, str], str]:
    """
    Parses simple Obsidian/YAML properties at the top of the file.

    Supports the form:
        ---
        Latex Type: Chapter
        Latex Parent: Theory
        ---
    """
    match = re.match(r"\A---\s*\n(?P<props>.*?)\n---\s*\n?", markdown, flags=re.DOTALL)

    if not match:
        return {}, markdown

    props_text = match.group("props")
    props: dict[str, str] = {}

    for line in props_text.splitlines():
        line = line.strip()

        if not line or line.startswith("#"):
            continue

        if ":" not in line:
            continue

        key, value = line.split(":", 1)
        props[key.strip()] = clean_yaml_scalar(value)

    body = markdown[match.end():]
    return props, body


def strip_properties(markdown: str) -> str:
    _, body = parse_frontmatter(markdown)
    return body


def remove_heading_numbering(title: str) -> str:
    """
    Removes cautious beginning numbering from headings only.

    Examples:
    1) My heading       -> My heading
    1. My heading       -> My heading
    1.2. My heading     -> My heading
    1.2) My heading     -> My heading
    """
    return re.sub(r"^\s*\d+(?:\.\d+)*[.)]\s+", "", title)


def split_appendix_title(title: str) -> tuple[bool, str]:
    """Remove 'Appendix', an optional letter, and its punctuation from a heading.

    Accepted forms include 'Appendix: Title', 'Appendix Title',
    'Appendix A: Title', 'Appendix B) Title', and 'Appendix C - Title'.
    """
    title = title.strip()
    match = re.match(r"(?i)^appendix\b\s*(.*)$", title)
    if not match:
        return False, title

    rest = match.group(1).strip()
    rest = re.sub(r"^[:.)\-–]\s*", "", rest)
    # Only discard a single-letter appendix identifier, not a title word.
    rest = re.sub(r"^[A-Za-z](?:\s*[:.)\-–]\s*|\s+)", "", rest)
    if re.fullmatch(r"[A-Za-z]", rest):
        rest = ""
    return True, rest.strip() or "Appendix"


def raw_prefix_from_title(title: str) -> str:
    """
    Examples:
    Theory                    -> thy
    Qubits and Quantum Gates  -> qus
    Transmon Qubit            -> trt
    """
    stem = re.sub(r"[^A-Za-z0-9]", "", title.strip()).lower()

    if len(stem) >= 3:
        return stem[:2] + stem[-1]

    if stem:
        return stem

    return "x"


def normalize_latex_type(value: str) -> str:
    value = value.strip().lower()

    if value == "chapter":
        return "chapter"

    if value == "section":
        return "section"

    if value == "article":
        return "article"

    return ""


def make_prefix_for_note(title: str, latex_type: str, latex_parent: str | None) -> str:
    title_prefix = raw_prefix_from_title(title)

    if latex_type == "chapter":
        return title_prefix

    if latex_parent:
        return f"{raw_prefix_from_title(latex_parent)}_{title_prefix}"

    return title_prefix


def make_note_info(path: Path, markdown: str, state: ConversionState, force: bool = False) -> NoteInfo | None:
    props, _ = parse_frontmatter(markdown)

    raw_type = get_prop(props, "Latex Type")

    if not raw_type and not force:
        return None

    latex_type = normalize_latex_type(raw_type)

    if not latex_type:
        if raw_type:
            state.warn(
                f"{path.name}: unknown Latex Type '{raw_type}', using Section"
            )
        else:
            state.warn(
                f"{path.name}: missing Latex Type property, using Section"
            )
        latex_type = "section"

    latex_parent_raw = get_prop(props, "Latex Parent")
    latex_parent = normalize_note_reference(latex_parent_raw) if latex_parent_raw else None

    if latex_type == "section" and not latex_parent:
        state.warn(
            f"{path.name}: Latex Type is Section but Latex Parent is missing; "
            "using an un-namespaced section prefix"
        )

    title = path.stem.strip()
    prefix = make_prefix_for_note(title, latex_type, latex_parent)

    if latex_type == "chapter":
        note_label = "ch"
        heading_label = "sec"
    elif latex_type == "article":
        note_label = "doc"
        heading_label = "sec"
    else:
        note_label = "sec"
        heading_label = "subsec"

    return NoteInfo(
        title=title,
        path=path,
        latex_type=latex_type,
        latex_parent=latex_parent,
        prefix=prefix,
        note_label=note_label,
        heading_label=heading_label,
    )


def resolve_document_level(source_path: Path, current_info: NoteInfo | None, state: ConversionState) -> str:
    if DOCUMENT_LEVEL in {"chapter", "section", "article"}:
        return DOCUMENT_LEVEL

    if current_info is not None:
        return current_info.latex_type

    state.warn(f"{source_path.name}: could not resolve document level; using Section")
    return "section"


def strip_references_section(markdown: str) -> str:
    """
    Removes everything from a heading called References onward.
    """
    parts = re.split(r"(?mi)^#{1,6}\s*References\s*$", markdown, maxsplit=1)
    return parts[0].rstrip()


def slugify_label(text: str) -> str:
    text = remove_heading_numbering(text)
    text = text.lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    text = text.strip("-")
    return text or "section"


def escape_latex_text(text: str) -> str:
    r"""Escape common text-mode specials without damaging existing LaTeX escapes."""
    text = re.sub(r"(?<!\\)&", r"\&", text)
    text = re.sub(r"(?<!\\)%", r"\%", text)
    text = re.sub(r"(?<!\\)#", r"\#", text)
    return text


def escape_latex_table_text(text: str) -> str:
    """
    Escapes text-mode table cells without double-escaping existing LaTeX escapes.
    Deliberately does not escape underscores.
    """
    text = re.sub(r"(?<!\\)&", r"\\&", text)
    text = re.sub(r"(?<!\\)%", r"\\%", text)
    text = re.sub(r"(?<!\\)#", r"\\#", text)
    return text


def convert_percent_signs(text: str) -> str:
    r"""
    Converts unescaped % into \%.
    Leaves already escaped \% unchanged.
    """
    return re.sub(r"(?<!\\)%", r"\\%", text)


def convert_bold(text: str) -> str:
    return re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", text)


def convert_markdown_citations(text: str) -> str:
    r"""
    [@tag] -> \cite{tag}
    [@tag1; @tag2] -> \cite{tag1,tag2}
    @tag -> \cite{tag}
    Allows dots in citation keys.
    """
    key = r"[A-Za-z0-9_:\-\.]+"

    def bracket_repl(match: re.Match) -> str:
        tags = re.findall(rf"@({key})", match.group(1))
        return r"\cite{" + ",".join(tags) + "}" if tags else match.group(0)

    text = re.sub(
        rf"\[((?:\s*@{key}(?:\s*;\s*)?)+)\]",
        bracket_repl,
        text,
    )

    text = re.sub(
        rf"(?<![\w\\])@({key})",
        r"\\cite{\1}",
        text,
    )

    return text


def latex_hyper_ref(ref_word: str, label: str) -> str:
    if label.startswith("doc:"):
        # Article body anchors have no numbered section counter.
        return rf"\hyperref[{label}]{{{ref_word}}}"
    return rf"\hyperref[{label}]{{{ref_word}~\ref*{{{label}}}}}"


def ref_word_from_label(label: str) -> str:
    if label.startswith("app:"):
        return "Appendix"

    if label.startswith("ch:"):
        return "Chapter"

    if label.startswith("doc:"):
        return "Article"

    return "Section"


def heading_level_info(markdown_level: int, document_level: str) -> tuple[str, str, str]:
    """
    Returns:
        LaTeX command, label prefix, reference word
    """
    if document_level in {"chapter", "article"}:
        table = {
            2: ("section", "sec", "Section"),
            3: ("subsection", "subsec", "Section"),
            4: ("subsubsection", "subsubsec", "Section"),
            5: ("paragraph", "par", "Section"),
            6: ("subparagraph", "subpar", "Section"),
        }
    else:
        table = {
            2: ("subsection", "subsec", "Section"),
            3: ("subsubsection", "subsubsec", "Section"),
            4: ("paragraph", "par", "Section"),
            5: ("subparagraph", "subpar", "Section"),
            6: ("subparagraph", "subpar", "Section"),
        }

    return table[markdown_level]


def build_heading_ref_map(
    markdown: str,
    file_prefix: str,
    document_level: str,
    state: ConversionState | None = None,
    source_name: str = "",
) -> dict[str, tuple[str, str]]:
    refs: dict[str, tuple[str, str]] = {}

    appendix_base_level: int | None = None

    pattern = re.compile(
        r"(?m)^(?P<marks>#{2,6})\s*(?P<title>.+?)\s*$"
    )

    for match in pattern.finditer(markdown):
        markdown_level = len(match.group("marks"))

        title = match.group("title").strip()
        title = remove_heading_numbering(title)

        is_appendix, clean_title = split_appendix_title(title)

        if is_appendix:
            appendix_base_level = markdown_level
            label_prefix = "app"
            ref_word = "Appendix"
            title = clean_title
        elif appendix_base_level is not None and markdown_level > appendix_base_level:
            _, label_prefix, ref_word = appendix_heading_level_info(
                markdown_level,
                appendix_base_level,
            )
        else:
            appendix_base_level = None
            _, label_prefix, ref_word = heading_level_info(markdown_level, document_level)

        slug = slugify_label(title)
        label = f"{label_prefix}:{file_prefix}_{slug}"

        if slug in refs and state is not None:
            state.warn(
                f"{source_name}: duplicate heading slug '{slug}' while building heading map"
            )
            continue

        refs[slug] = (ref_word, label)

    return refs


def build_project_index(root: Path, source_path: Path, state: ConversionState) -> dict[str, NoteInfo]:
    """
    Scans Markdown files under root.

    Only files with Latex Type are included by default.
    The source file is included even if it is missing Latex Type, so conversion can continue.
    """
    root = root.resolve()
    source_path = source_path.resolve()

    note_index: dict[str, NoteInfo] = {}
    note_bodies: dict[str, str] = {}

    for path in sorted(root.rglob("*.md")):
        try:
            markdown = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            state.warn(f"{path}: could not read as UTF-8; skipping")
            continue

        force = path.resolve() == source_path
        info = make_note_info(path, markdown, state, force=force)

        if info is None:
            continue

        if info.title in note_index:
            state.warn(
                f"duplicate note title '{info.title}' in project index; "
                f"keeping {note_index[info.title].path} and ignoring {path}"
            )
            continue

        _, body = parse_frontmatter(markdown)
        body = strip_references_section(body)

        note_index[info.title] = info
        note_bodies[info.title] = body

    # Different notes must not share one LaTeX namespace.
    prefix_owner: dict[str, str] = {}
    for title, info in note_index.items():
        earlier = prefix_owner.get(info.prefix)
        if earlier is not None:
            state.warn(
                f"prefix collision '{info.prefix}' between notes '{earlier}' and '{title}'"
            )
        else:
            prefix_owner[info.prefix] = title

    for title, info in note_index.items():
        # Only tagged display equations receive generated equation labels.
        info.equation_tags = {
            match.group(1).strip()
            for block in re.findall(r"\$\$(.*?)\$\$", note_bodies[title], flags=re.DOTALL)
            for match in re.finditer(r"\\tag\{([^}]+)\}", block)
        }
        info.figure_tags = {
            m.group(1).strip() for m in re.finditer(
                r"!\[\[[^\]\n]*?\|fig:([^|\]\n]+)", note_bodies[title]
            )
        }
        info.table_tags = {
            m.group(1).strip() for m in re.finditer(
                r"(?mi)^>\s*\[!(?:table|long-table|longtable)\s*:\s*([^\]\s]+)", note_bodies[title]
            )
        }
        info.headings = build_heading_ref_map(
            note_bodies[title],
            info.prefix,
            info.latex_type,
            state=state,
            source_name=info.path.name,
        )

    return note_index


def appendix_heading_level_info(markdown_level: int, appendix_base_level: int) -> tuple[str, str, str]:
    relative_level = markdown_level - appendix_base_level

    if relative_level <= 0:
        return "section", "app", "Appendix"

    table = {
        1: ("subsection", "subapp", "Appendix"),
        2: ("subsubsection", "subsubapp", "Appendix"),
        3: ("paragraph", "parapp", "Appendix"),
        4: ("subparagraph", "subparapp", "Appendix"),
    }

    return table.get(relative_level, ("subparagraph", "subparapp", "Appendix"))


def convert_headings(
    text: str,
    file_prefix: str,
    document_level: str,
    state: ConversionState,
) -> str:
    appendix_base_level: int | None = None

    def repl(match: re.Match) -> str:
        nonlocal appendix_base_level

        markdown_level = len(match.group("marks"))

        title = match.group("title").strip()
        title = remove_heading_numbering(title)

        is_appendix, clean_title = split_appendix_title(title)

        if is_appendix:
            appendix_base_level = markdown_level
            command = "section"
            label_prefix = "app"
            title = clean_title
        elif appendix_base_level is not None and markdown_level > appendix_base_level:
            command, label_prefix, _ = appendix_heading_level_info(
                markdown_level,
                appendix_base_level,
            )
        else:
            appendix_base_level = None
            command, label_prefix, _ = heading_level_info(markdown_level, document_level)

        label_slug = slugify_label(title)
        label = f"{label_prefix}:{file_prefix}_{label_slug}"

        state.register_label(label, f"heading '{title}'")

        title_latex = escape_latex_text(title)

        return (
            rf"\{command}{{{title_latex}}}" "\n"
            rf"\label{{{label}}}"
        )

    return re.sub(
        r"(?m)^(?P<marks>#{2,6})\s*(?P<title>.+?)\s*$",
        repl,
        text,
    )

def convert_legacy_rm(text: str) -> str:
    r"""Convert legacy math-font switches, retaining the complete roman argument.

    Examples: \phi_{\rm err} -> \phi_{\mathrm{err}}
              \rm{GHz}       -> \mathrm{GHz}
    """
    text = re.sub(r"\{\s*\\rm\s+([A-Za-z]+)\s*\}", r"{\\mathrm{\1}}", text)
    text = re.sub(r"\\rm\s*\{([^{}]+)\}", r"\\mathrm{\1}", text)
    text = re.sub(r"\\rm\s+([A-Za-z]+)", r"\\mathrm{\1}", text)
    return re.sub(r"\\rm(?![A-Za-z])", r"\\mathrm", text)


def normalize_caption_latex(text: str) -> str:
    text = text.strip()
    text = text.replace(r"\_", "_")
    text = text.replace(r"\*", "*")
    text = text.replace(r"\\,", r"\,")
    text = text.replace(r"\\%", r"\%")
    return text


def format_caption(raw_caption: str) -> CaptionParts:
    r"""
    **Title.** Long explanation.

    becomes:

    short: Title
    long:  \textbf{Title.} Long explanation.
    label source: Title
    """
    caption = normalize_caption_latex(raw_caption)

    bold_title_match = re.match(
        r"^\*\*(?P<title>.+?)\*\*\s*(?P<rest>.*)$",
        caption,
        flags=re.DOTALL,
    )

    if bold_title_match:
        title = bold_title_match.group("title").strip()
        rest = bold_title_match.group("rest").strip()

        short_title = re.sub(r"\.\s*$", "", title).strip()

        title_latex = escape_latex_text(title)
        rest_latex = escape_latex_text(rest)
        short_latex = escape_latex_text(short_title)

        if rest_latex:
            long_latex = rf"\textbf{{{title_latex}}} {rest_latex}"
        else:
            long_latex = rf"\textbf{{{title_latex}}}"

        return CaptionParts(
            short_latex=short_latex,
            long_latex=long_latex,
            label_source=short_title,
        )

    short = re.split(r"\.\s+", caption, maxsplit=1)[0].strip()
    short = re.sub(r"\.\s*$", "", short).strip()

    if not short:
        short = caption

    return CaptionParts(
        short_latex=escape_latex_text(short),
        long_latex=escape_latex_text(caption),
        label_source=short,
    )


def make_prefixed_label(kind: str, tag: str, file_prefix: str) -> str:
    """
    kind: 'fig', 'eq', or 'tab'
    tag:  '1', 'A.7', 'thy_A.7', 'eq:A.7', etc.
    """
    tag = tag.strip()
    tag = re.sub(rf"^{kind}:", "", tag)

    if tag.startswith(file_prefix + "_"):
        return f"{kind}:{tag}"

    return f"{kind}:{file_prefix}_{tag}"


# Figures are included at their natural physical dimensions whenever they fit.
# This limit is only a fallback for artwork that would not fit alongside its
# typeset caption on a single page, with room left clear of the page footer.
FIGURE_FIT_MAX_HEIGHT = r"0.96\textheight"


FIGURE_PLACEMENTS = {
    "first": "!t",      # Move after first-reference paragraph; text may share the page.
    "top": "!t",        # Keep source position; top-of-page float, not an automatic float-only page.
    "near": "!htbp",    # Keep source position; allow here/top/bottom/page.
    "section": "H",     # Anchor at source and retain section-barrier semantics.
    "here": "H",         # Original nonfloating behavior (float package).
}

# Keep table float modes independent of the figure-anchoring policy.
TABLE_PLACEMENTS = {
    "first": "!tbp",
    "top": "!tbp",
    "near": "!htbp",
    "section": "!htbp",
    "here": "H",
}


def figure_placement(parts: list[str], default: str, state: ConversionState) -> str:
    """Resolve the optional |place:first/top/near/section/here| token."""
    modes = [part[6:].strip().lower() for part in parts[1:] if part.lower().startswith("place:")]
    if len(modes) > 1:
        state.warn("figure embed has multiple place: directives; using the last")
    mode = modes[-1] if modes else default
    if mode not in FIGURE_PLACEMENTS:
        state.warn(f"unknown figure placement '{mode}'; falling back to '{default}'")
        return default
    return mode


def _paragraph_end_after(text: str, position: int) -> int:
    """Return a safe boundary after the paragraph containing a figure reference."""
    boundary = re.search(r"\n[ \t]*\n|\n(?=#{2,6}[ \t]+)", text[position:])
    if boundary:
        return position + boundary.end()
    line_end = text.find("\n", position)
    return len(text) if line_end < 0 else line_end + 1


def relocate_figures_to_first_reference(text: str, default: str, state: ConversionState) -> str:
    r"""Move standalone figures in 'first' mode after the paragraph of first local \ref{fig:tag}.

    Do not move section-anchored figures or inline embeds. Moving before LaTeX conversion
    keeps labels, captions, and the Obsidian source untouched.
    """
    if default != "first" and "place:first" not in text.lower():
        return text
    embeds = re.compile(r"(?m)^[ \t]*!\[\[(?P<inside>[^\]\n]+)\]\][ \t]*(?:\n|$)")
    candidates = []
    for found in embeds.finditer(text):
        parts = [part.strip() for part in found.group("inside").split("|")]
        overrides = [part[6:].strip().lower() for part in parts[1:] if part.lower().startswith("place:")]
        if (overrides[-1] if overrides else default) != "first":
            continue
        tags = [part[4:].strip() for part in parts[1:] if part.lower().startswith("fig:")]
        if not tags:
            if "place:first" in found.group("inside").lower():
                state.warn(f"figure '{parts[0]}' needs fig:TAG for first-reference placement; keeping source location")
            continue
        candidates.append((found, tags[0], parts[0]))
    if not candidates:
        return text

    # Preserve a paragraph break where a standalone figure was removed. Otherwise
    # text immediately after the embed can be mistaken for part of the preceding
    # reference paragraph, and the figure is wrongly inserted after that text.
    stripped_parts, cursor = [], 0
    for found, _, _ in candidates:
        stripped_parts.extend((text[cursor:found.start()], "\n"))
        cursor = found.end()
    stripped_parts.append(text[cursor:])
    clean_text = "".join(stripped_parts)

    insertions: list[tuple[int, int, str]] = []
    not_moved = []
    for order, (found, tag, filename) in enumerate(candidates):
        first_match = None
        for citation in re.finditer(r"\\ref\{fig:([^}]+)\}", clean_text):
            line_start = clean_text.rfind("\n", 0, citation.start()) + 1
            line_end = clean_text.find("\n", citation.end())
            line_end = len(clean_text) if line_end < 0 else line_end
            if "![[" in clean_text[line_start:line_end]:
                continue  # A caption reference is not a prose mention.
            if tag in expand_reference_tags(citation.group(1)):
                first_match = citation
                break
        embed_line = found.group(0).strip()
        if first_match is None:
            if "place:first" in found.group("inside").lower():
                state.warn(f"figure '{filename}' has no matching local \\ref{{fig:{tag}}}; keeping source location")
            # Preserve original position using the clean-text offset.
            offset = sum((m.end() - m.start() - 1) for m, _, _ in candidates if m.start() < found.start())
            not_moved.append((found.start() - offset, order, embed_line))
            continue
        source_section = len(re.findall(r"(?m)^##[ \t]+", text[:found.start()]))
        reference_section = len(re.findall(r"(?m)^##[ \t]+", clean_text[:first_match.start()]))
        if source_section != reference_section:
            if "place:first" in found.group("inside").lower():
                state.warn(f"figure '{filename}' first reference is in a different section; keeping source location")
            offset = sum((m.end() - m.start() - 1) for m, _, _ in candidates if m.start() < found.start())
            not_moved.append((found.start() - offset, order, embed_line))
            continue
        insertion_pos = _paragraph_end_after(clean_text, first_match.end())
        insertions.append((insertion_pos, order, embed_line))
    all_insertions = sorted(insertions + not_moved, key=lambda item: (item[0], item[1]))
    result, cursor = [], 0
    for position, _, embed_line in all_insertions:
        result.append(clean_text[cursor:position])
        result.append("\n" + embed_line + "\n\n")
        cursor = position
    result.append(clean_text[cursor:])
    updated = "".join(result)
    original_order = [m.group("inside") for m in embeds.finditer(text)]
    updated_order = [m.group("inside") for m in embeds.finditer(updated)]
    if original_order != updated_order:
        state.warn("first-reference placement would reorder figure numbering; keeping source positions instead")
        return text
    return updated


def convert_figures(
    text: str, file_prefix: str, state: ConversionState,
    placement: str = "first", figure_dir: str = "Chapters/Figures",
) -> str:
    """Include artwork at native size when it fits, scaling down only if needed.

    A .svg input selects the .pdf generated separately by svg_to_pdf_batch.py;
    other extensions are unchanged. Obsidian display-width hints are ignored.
    Only if the native artwork exceeds the available line width or the safe
    caption-aware page height does graphicx scale it down. No image is enlarged.
    The caption is typeset once, measured and reused without duplicating labels.
    """
    pattern = re.compile(r"!\[\[([^\]]+)\]\]")

    def repl(match: re.Match) -> str:
        parts = [p.strip() for p in match.group(1).split("|")]
        source_filename = parts[0]
        filename = source_filename
        mode = figure_placement(parts, placement, state)
        span_parts = [p[5:].strip().lower() for p in parts[1:] if p.lower().startswith("span:")]
        span = span_parts[-1] if span_parts else "column"
        if span not in {"column", "both"}:
            state.warn(f"figure '{source_filename}' has invalid span:{span}; using span:column")
            span = "column"
        if len(span_parts) > 1:
            state.warn(f"figure '{source_filename}' has multiple span: options; using the last")
        if Path(filename).suffix.lower() == ".svg":
            filename = str(Path(filename).with_suffix(".pdf"))

        fig_tag = None
        desc = ""
        for part in parts[1:]:
            if part.startswith("fig:"):
                fig_tag = part.removeprefix("fig:").strip()
            elif part.startswith("desc:"):
                desc = part.removeprefix("desc:").strip()
        if fig_tag is None:
            fig_tag = Path(source_filename).stem
            state.warn(f"figure '{source_filename}' missing fig: tag; using filename stem")
        if not desc:
            state.warn(f"figure '{source_filename}' missing desc:")

        caption = format_caption(desc)
        label = make_prefixed_label("fig", fig_tag, file_prefix)
        state.register_label(label, f"figure '{source_filename}'")
        wide = span == "both"
        if wide and mode == "here":
            state.warn(f"figure '{source_filename}': span:both cannot use place:here in two-column LaTeX; using top")
            mode = "top"
        float_option = "!t" if wide else FIGURE_PLACEMENTS[mode]
        environment = "figure*" if wide else "figure"
        after = r"\FloatBarrier" + "\n" if mode == "section" else ""
        latex_figure_dir = figure_dir.replace("\\", "/").rstrip("/")
        path = (latex_figure_dir + "/" if latex_figure_dir else "") + filename.replace("\\", "/")
        return (
            rf"\begin{{{environment}}}[{float_option}]" "\n"
            r"    \centering" "\n"
            # Allocate the caption box once per LaTeX document; conversion itself
            # does not need (or change) any preamble definitions.
            r"    \ifdefined\mdToLatexCaptionBox\else\newsavebox{\mdToLatexCaptionBox}\fi" "\n"
            # graphicx uses TeX scratch dimensions (including \dimen0) while
            # processing width/height options. Preserve the actual height cap.
            r"    \ifdefined\mdToLatexFigureHeight\else\newdimen\mdToLatexFigureHeight\fi" "\n"
            r"    \ifdefined\mdToLatexNaturalImageBox\else\newsavebox{\mdToLatexNaturalImageBox}\fi" "\n"
            r"    \setbox\mdToLatexCaptionBox=\vbox{" "\n"
            r"        \hsize=\linewidth" "\n"
            rf"        \caption[{caption.short_latex}]{{{caption.long_latex}}}" "\n"
            rf"        \label{{{label}}}" "\n"
            r"    }" "\n"
            # Measure the real (native) graphic once. Normal-sized images are
            # reused as-is: no graphicx width, height or scale options apply.
            rf"    \sbox{{\mdToLatexNaturalImageBox}}{{\includegraphics{{{path}}}}}" "\n"
            # Only oversize artwork needs scaling. Allow most of the text area,
            # subtracting the actual caption and leaving room for float spacing.
            rf"    \mdToLatexFigureHeight=\dimexpr {FIGURE_FIT_MAX_HEIGHT}-\ht\mdToLatexCaptionBox-\dp\mdToLatexCaptionBox-\baselineskip\relax" "\n"
            r"    \ifdim\mdToLatexFigureHeight<1pt \mdToLatexFigureHeight=1pt\fi" "\n"
            r"    \ifdim\wd\mdToLatexNaturalImageBox>\linewidth" "\n"
            rf"        \includegraphics[width=\linewidth,height=\the\mdToLatexFigureHeight,keepaspectratio]{{{path}}}" "\n"
            r"    \else" "\n"
            r"        \ifdim\dimexpr\ht\mdToLatexNaturalImageBox+\dp\mdToLatexNaturalImageBox\relax>\mdToLatexFigureHeight" "\n"
            rf"            \includegraphics[width=\linewidth,height=\the\mdToLatexFigureHeight,keepaspectratio]{{{path}}}" "\n"
            r"        \else" "\n"
            r"            \usebox{\mdToLatexNaturalImageBox}" "\n"
            r"        \fi" "\n"
            r"    \fi" "\n"
            r"    \par\nobreak\noindent\usebox{\mdToLatexCaptionBox}" "\n"
            rf"\end{{{environment}}}" "\n"
            + after
        )

    return pattern.sub(repl, text)


CROSS_NOTE_EQUATION_REF_RE = re.compile(
    r"\bEqs?\.[ \t]*"
    r"(?:\((?P<parenthesized>[A-Za-z0-9_.-]+(?:[ \t]*,[ \t]*[A-Za-z0-9_.-]+)*)\)"
    r"|(?P<bare>[A-Za-z0-9_.-]+(?:[ \t]*,[ \t]*[A-Za-z0-9_.-]+)*))"
    r"[ \t]+(?:of|in)[ \t]+"
    r"\[\[(?P<note>[^]#|]+)(?:\#[^]|]+)?(?:\|[^]]*)?\]\]",
    flags=re.IGNORECASE,
)


def expand_reference_tags(raw: str) -> list[str]:
    r"""Parse comma lists and numeric ranges, including Equation Citator's 1.1~3."""
    def numeric_parts(value: str) -> tuple[str, int] | None:
        m = re.fullmatch(r"(.*?)(\d+)", value)
        return (m.group(1), int(m.group(2))) if m else None

    out: list[str] = []
    for item in raw.split(","):
        item = item.strip()
        if not item:
            continue
        m = re.fullmatch(r"(.+?)\s*[~–-]\s*(.+)", item)
        if m:
            first, last = m.group(1).strip(), m.group(2).strip()
            a, b = numeric_parts(first), numeric_parts(last)
            if a is not None and b is not None:
                prefix_a, begin = a
                prefix_b, finish = b
                if not prefix_b and prefix_a:
                    prefix_b = prefix_a  # 1.1~3 denotes 1.1 through 1.3
                if prefix_a == prefix_b and begin <= finish and finish - begin < 1000:
                    out.extend(f"{prefix_a}{n}" for n in range(begin, finish + 1))
                    continue
        out.append(item)
    return list(dict.fromkeys(out))


def collapse_consecutive_tags(tags: list[str]) -> list[tuple[str, str]]:
    """Return inclusive (first, last) groups without changing input order."""
    def parts(tag: str) -> tuple[str, int] | None:
        m = re.fullmatch(r"(.*?)(\d+)", tag)
        return (m.group(1), int(m.group(2))) if m else None

    if not tags:
        return []
    groups: list[tuple[str, str]] = []
    first = last = tags[0]
    for tag in tags[1:]:
        a, b = parts(last), parts(tag)
        if a is not None and b is not None and a[0] == b[0] and b[1] == a[1] + 1:
            last = tag
        else:
            groups.append((first, last))
            first = last = tag
    groups.append((first, last))
    return groups


def format_object_reference(kind: str, tags: list[str], file_prefix: str) -> str:
    """Render one clickable phrase, using ranges for consecutive tags."""
    display_kind = {"eq": ("Eq.", "Eqs.", True), "fig": ("Fig.", "Figs.", False), "tab": ("Table", "Tables", False)}
    singular, plural, parentheses = display_kind[kind]
    groups = collapse_consecutive_tags(tags)
    if not groups:
        return ""
    pieces = []
    for first, last in groups:
        left = make_prefixed_label(kind, first, file_prefix)
        item = rf"\ref*{{{left}}}"
        if first != last:
            right = make_prefixed_label(kind, last, file_prefix)
            item += rf"--\ref*{{{right}}}"
        pieces.append((left, item))
    phrase = singular if len(tags) == 1 else plural
    if len(tags) == 1:
        body = pieces[0][1]
        if parentheses:
            body = f"({body})"
        return rf"\hyperref[{pieces[0][0]}]{{{phrase}~{body}}}"
    # For figure citations, make "Figs." part of the first hyperlink too.
    # Keep subsequent disjoint groups linked to their own first figure, rather
    # than making all references navigate to the first figure in the list.
    if kind == "fig":
        first_label, first_item = pieces[0]
        first_link = rf"\hyperref[{first_label}]{{{phrase}~{first_item}}}"
        following = ", ".join(rf"\hyperref[{label}]{{{item}}}" for label, item in pieces[1:])
        return first_link + (", " + following if following else "")
    # Equations and tables preserve their existing multi-reference formatting.
    body = ", ".join(rf"\hyperref[{label}]{{{item}}}" for label, item in pieces)
    if parentheses:
        body = f"({body})"
    return rf"{phrase}~{body}"


def validate_object_refs(kind: str, tags: list[str], valid_tags: set[str] | None, state: ConversionState | None, note: str) -> None:
    if valid_tags is None or state is None:
        return
    name = {"eq": "equation", "fig": "figure", "tab": "table"}[kind]
    for tag in tags:
        if tag not in valid_tags:
            state.warn(f"{name} tag '{tag}' not found in note '{note}'")


def validate_equation_refs(tags: list[str], valid_tags: set[str] | None, state: ConversionState | None, note: str) -> None:
    validate_object_refs("eq", tags, valid_tags, state, note)


def convert_cross_note_equation_refs(
    text: str,
    note_index: dict[str, NoteInfo],
    state: ConversionState,
) -> str:
    r"""Resolve Eq. (3) of [[Note]] and Eqs. (3-6, 8) of [[Note]]."""
    def repl(match: re.Match) -> str:
        note_name = normalize_note_reference(match.group("note"))
        target = lookup_note(note_name, note_index, state)
        if target is None:
            return match.group(0)
        tags = expand_reference_tags(match.group("parenthesized") or match.group("bare"))
        validate_equation_refs(tags, target.equation_tags, state, target.title)
        return format_object_reference("eq", tags, target.prefix) or match.group(0)
    return CROSS_NOTE_EQUATION_REF_RE.sub(repl, text)


def convert_plugin_cross_note_refs(text: str, note_index: dict[str, NoteInfo], state: ConversionState) -> str:
    r"""Resolve Equation Citator footnote links: \ref{eq:1^{2.3}} and [^1]: [[Note]]."""
    footnote = re.compile(r"(?m)^\[\^(?P<id>[^\]\s]+)\]:\s*\[\[(?P<note>[^]|#]+)(?:#[^]|]+)?(?:\|[^]]*)?\]\]\s*$")
    targets = {m.group("id"): m.group("note").strip() for m in footnote.finditer(text)}
    used: set[str] = set()
    pattern = re.compile(r"(?P<prefix>(?:Eqs?\.|Figs?\.|Tables?\.?)\s*)?\$?\\ref\{(?P<kind>eq|fig|tab|table):(?P<id>[^{}^,\s]+)\^\{(?P<tags>[^{}]+)\}\}\$?")
    def repl(m: re.Match) -> str:
        ident, kind = m.group("id"), m.group("kind")
        if ident not in targets:
            state.warn(f"Equation Citator cross-file footnote '[^{ident}]' not found")
            return m.group(0)
        target = lookup_note(targets[ident], note_index, state)
        if target is None:
            return m.group(0)
        used.add(ident)
        kind = "tab" if kind == "table" else kind
        tags = expand_reference_tags(m.group("tags"))
        valid = {"eq": target.equation_tags, "fig": target.figure_tags, "tab": target.table_tags}[kind]
        validate_object_refs(kind, tags, valid, state, target.title)
        return format_object_reference(kind, tags, target.prefix) or m.group(0)
    text = pattern.sub(repl, text)
    if used:
        text = footnote.sub(lambda m: "" if m.group("id") in used else m.group(0), text)
    return text


def convert_figure_and_equation_refs(
    text: str, file_prefix: str,
    state: ConversionState | None = None,
    valid_equation_tags: set[str] | None = None,
    valid_figure_tags: set[str] | None = None,
    valid_table_tags: set[str] | None = None,
    note_title: str = "current note",
) -> str:
    r"""Convert direct \ref citations for equations, figures and tables.

    Accept comma lists and Equation Citator numeric ranges (e.g. eq:1~4).
    Existing explicit prefixes are consumed to prevent 'Eq. Eq.' duplication.
    """
    fig_pattern = re.compile(
        r"(?P<prefix>Figs?\.\s*)?"
        r"\$?\\ref\{fig:(?P<tags>[^}]+)\}\$?"
        r"(?P<suffix>\s*\([a-zA-Z]\)|[a-zA-Z](?![a-zA-Z]))?"
    )
    def fig_repl(m: re.Match) -> str:
        tags = expand_reference_tags(m.group("tags"))
        if not tags:
            return m.group(0)
        validate_object_refs("fig", tags, valid_figure_tags, state, note_title)
        suffix = (m.group("suffix") or "").strip()
        if re.fullmatch(r"[a-zA-Z]", suffix):
            suffix = f"({suffix})"
        phrase = format_object_reference("fig", tags, file_prefix)
        # Keep panel letters within the same hyperlink.
        if suffix and len(tags) == 1:
            return phrase[:-1] + suffix + "}"
        return phrase + suffix
    text = fig_pattern.sub(fig_repl, text)

    eq_pattern = re.compile(r"(?P<prefix>Eqs?\.\s*)?\$?\\ref\{eq:(?P<tags>[^}]+)\}\$?")
    def eq_repl(m: re.Match) -> str:
        tags = expand_reference_tags(m.group("tags"))
        validate_equation_refs(tags, valid_equation_tags, state, note_title)
        return format_object_reference("eq", tags, file_prefix) or m.group(0)
    text = eq_pattern.sub(eq_repl, text)

    tab_pattern = re.compile(r"(?P<prefix>Tables?\.?(?:\s+|~))?\$?\\ref\{(?:table|tab):(?P<tags>[^}]+)\}\$?")
    def tab_repl(m: re.Match) -> str:
        tags = expand_reference_tags(m.group("tags"))
        validate_object_refs("tab", tags, valid_table_tags, state, note_title)
        return format_object_reference("tab", tags, file_prefix) or m.group(0)
    return tab_pattern.sub(tab_repl, text)

def convert_equations(text: str, file_prefix: str, state: ConversionState) -> str:
    pattern = re.compile(r"\$\$(.*?)\$\$", flags=re.DOTALL)

    def repl(match: re.Match) -> str:
        body = match.group(1).strip()
        tag_match = re.search(r"\\tag\{([^}]+)\}", body)

        if tag_match:
            eq_tag = tag_match.group(1).strip()
            body = re.sub(r"\s*\\tag\{[^}]+\}\s*", "", body).strip()

            label = make_prefixed_label("eq", eq_tag, file_prefix)
            state.register_label(label, f"equation tag '{eq_tag}'")

            body_lines = "\n".join(f"    {line}" for line in body.splitlines())

            return (
                "\n"
                r"\begin{equation}" "\n"
                f"{body_lines}\n"
                rf"    \label{{{label}}}" "\n"
                r"\end{equation}"
                "\n"
            )

        body_lines = "\n".join(f"    {line}" for line in body.splitlines())

        return (
            "\n"
            r"\begin{equation*}" "\n"
            f"{body_lines}\n"
            r"\end{equation*}"
            "\n"
        )

    return pattern.sub(repl, text)


def split_markdown_table_row(line: str) -> list[str] | None:
    """Split a pipe row while ignoring pipes inside inline math or code spans."""
    line = line.strip()
    if not line.startswith("|"):
        return None
    if line.endswith("|") and not line.endswith(r"\|"):
        line = line[:-1]
    line = line[1:]
    cells: list[str] = []
    buf: list[str] = []
    math_mode = False
    code_mode = False
    for i, char in enumerate(line):
        escaped = i > 0 and line[i - 1] == "\\" and (i < 2 or line[i - 2] != "\\")
        if char == "$" and not escaped and not code_mode:
            math_mode = not math_mode
        elif char == "`" and not escaped and not math_mode:
            code_mode = not code_mode
        if char == "|" and not escaped and not math_mode and not code_mode:
            cells.append("".join(buf).strip())
            buf = []
        else:
            buf.append(char)
    cells.append("".join(buf).strip())
    return cells


def is_markdown_table_separator(line: str) -> bool:
    cells = split_markdown_table_row(line)

    if not cells:
        return False

    return all(
        re.fullmatch(r":?-{3,}:?", cell.replace(" ", "")) is not None
        for cell in cells
    )


def markdown_table_alignment(separator_line: str, n_cols: int) -> str:
    cells = split_markdown_table_row(separator_line) or []
    aligns = []

    for cell in cells[:n_cols]:
        cell = cell.replace(" ", "")

        if cell.startswith(":") and cell.endswith(":"):
            aligns.append("c")
        elif cell.endswith(":"):
            aligns.append("r")
        else:
            aligns.append("l")

    while len(aligns) < n_cols:
        aligns.append("l")

    return "".join(aligns)


def normalize_table_latex(cell: str) -> str:
    """Normalize common double-escaped math spacing while retaining literal underscores."""
    cell = cell.strip()
    cell = cell.replace(r"\\,", r"\,")
    cell = cell.replace(r"\\%", r"\%")
    return cell


def is_math_like_table_cell(cell: str) -> bool:
    """Infer math mode only for a standalone mathematical expression.

    Explicit $...$ is preferred. Mixed prose/math cells are left alone, and
    text-mode commands generated by reference and citation conversion are not
    wrapped in math mode.
    """
    if not cell or "$" in cell:
        return False
    if re.search(r"\\(?:hyperref|ref\*?|cite|autoref|nameref|textbf|textit|url)\b", cell):
        return False
    if re.search(r",\s+[A-Za-z]", cell):
        return False
    if re.search(r"[A-Za-z]{2,}\s+[A-Za-z]{2,}", cell):
        return False
    return bool(re.search(r"\\[A-Za-z]+|\\_|(?<!\\)[_^]", cell))


def format_table_cell(cell: str, is_header: bool = False) -> str:
    cell = normalize_table_latex(cell)
    if is_header:
        return rf"\textbf{{{escape_latex_table_text(cell)}}}"
    if is_math_like_table_cell(cell):
        return f"${cell.replace(r'\_', '_')}$"
    return escape_latex_table_text(cell)


def convert_table_block(
    header: list[str],
    separator: str,
    rows: list[list[str]],
    state: ConversionState,
    caption: CaptionParts | None = None,
    label: str | None = None,
    long_table: bool = False,
    placement: str = "here",
    span: str = "column",
    width: str = "natural",
    columns: str | None = None,
) -> str:
    n_cols = len(header)
    align_spec = markdown_table_alignment(separator, n_cols)
    if columns:
        if len(columns) != n_cols or any(ch not in "lcrX" for ch in columns):
            state.warn(f"table columns '{columns}' must have {n_cols} characters from lcrX")
        else:
            align_spec = columns
    if width == "fit" and "X" not in align_spec:
        state.warn("width:fit table needs a cols: directive with at least one X column")
    if width == "natural" and "X" in align_spec:
        state.warn("cols: with X requires width:fit")
    if long_table and (span == "both" or width == "fit"):
        state.warn("longtable does not support span:both or width:fit in this converter")
    if span == "both" and placement == "here":
        state.warn("span:both table cannot use place:here in two-column LaTeX; using top")
        placement = "top"

    separator_count = len(split_markdown_table_row(separator) or [])
    if separator_count != n_cols:
        state.warn(f"table separator has {separator_count} columns; header has {n_cols}")
    for row_num, row in enumerate(rows, start=1):
        if len(row) != n_cols:
            state.warn(f"table body row {row_num} has {len(row)} columns; expected {n_cols}")

    def fix_row(row: list[str]) -> list[str]:
        # Pad short rows but never silently discard extra cells.
        return row + [""] * max(0, n_cols - len(row))

    if label:
        state.register_label(label, "table")

    if long_table:
        lines = [
            "",
            rf"\begin{{longtable}}{{{align_spec}}}",
        ]

        if caption and label:
            lines.append(
                rf"    \caption[{caption.short_latex}]{{{caption.long_latex}}}"
                rf"\label{{{label}}}\\"
            )
        elif caption:
            lines.append(
                rf"    \caption[{caption.short_latex}]{{{caption.long_latex}}}\\"
            )

        lines.extend(
            [
                r"    \toprule",
                "    "
                + " & ".join(format_table_cell(cell, is_header=True) for cell in fix_row(header))
                + r" \\",
                r"    \midrule",
                r"    \endfirsthead",
                r"    \toprule",
                "    "
                + " & ".join(format_table_cell(cell, is_header=True) for cell in fix_row(header))
                + r" \\",
                r"    \midrule",
                r"    \endhead",
            ]
        )

        for row in rows:
            lines.append(
                "    "
                + " & ".join(format_table_cell(cell) for cell in fix_row(row))
                + r" \\"
            )

        lines.extend(
            [
                r"    \bottomrule",
                r"\end{longtable}",
                "",
            ]
        )

        return "\n".join(lines)

    mode = "top" if placement == "auto" else placement
    if mode not in TABLE_PLACEMENTS:
        state.warn(f"invalid table placement '{mode}'; using top")
        mode = "top"
    environment = "table*" if span == "both" else "table"
    float_option = "!tp" if span == "both" else TABLE_PLACEMENTS[mode]
    tab_env = "tabularx" if width == "fit" else "tabular"
    tab_spec = rf"{{\linewidth}}{{{align_spec}}}" if width == "fit" else rf"{{{align_spec}}}"
    lines = [
        "",
        rf"\begin{{{environment}}}[{float_option}]",
        r"    \centering",
    ]

    if caption:
        lines.append(rf"    \caption[{caption.short_latex}]{{{caption.long_latex}}}")

    if label:
        lines.append(rf"    \label{{{label}}}")

    lines.extend(
        [
            rf"    \begin{{{tab_env}}}{tab_spec}",
            r"        \toprule",
            "        "
            + " & ".join(format_table_cell(cell, is_header=True) for cell in fix_row(header))
            + r" \\",
            r"        \midrule",
        ]
    )

    for row in rows:
        lines.append(
            "        "
            + " & ".join(format_table_cell(cell) for cell in fix_row(row))
            + r" \\"
        )

    lines.extend(
        [
            r"        \bottomrule",
            rf"    \end{{{tab_env}}}",
            rf"\end{{{environment}}}",
            r"\FloatBarrier" if mode == "section" else "",
            "",
        ]
    )

    return "\n".join(lines)


TABLE_CALLOUT_RE = re.compile(
    r"^>\s*\[!(?P<kind>table|long-table|longtable)(?:\s*:\s*(?P<tag>[^\]\s]+))?\]\s*(?P<caption>.*)$",
    flags=re.IGNORECASE,
)


def strip_blockquote_marker(line: str) -> str:
    return re.sub(r"^>\s?", "", line)


def parse_table_rows_from_lines(lines: list[str], start: int) -> tuple[list[str], str, list[list[str]], int] | None:
    if start + 1 >= len(lines):
        return None

    header = split_markdown_table_row(lines[start])
    separator_line = lines[start + 1]

    if header is None or not is_markdown_table_separator(separator_line):
        return None

    rows: list[list[str]] = []
    i = start + 2

    while i < len(lines):
        row = split_markdown_table_row(lines[i])

        if row is None:
            break

        if is_markdown_table_separator(lines[i]):
            i += 1
            continue

        rows.append(row)
        i += 1

    return header, separator_line, rows, i


def remove_visible_table_number(caption: str) -> str:
    """Let LaTeX number the table instead of repeating 'Table 1.' in its caption."""
    return re.sub(r"(?i)^\s*Table\s+[A-Za-z0-9]+\s*[.):\-]\s*", "", caption).strip()


def parse_table_float_options(lines: list[str], state: ConversionState, default: str) -> tuple[list[str], dict[str, str | None]]:
    """Read invisible Obsidian HTML comments: <!-- latex: place:top span:both width:fit cols:lXrr -->."""
    options: dict[str, str | None] = {"placement": default, "span": "column", "width": "natural", "columns": None}
    cleaned = []
    pattern = re.compile(r"<!--\s*latex:\s*(.*?)\s*-->", flags=re.I)
    for line in lines:
        for match in pattern.finditer(line):
            for token in match.group(1).split():
                if ":" not in token:
                    state.warn(f"invalid LaTeX table directive '{token}'")
                    continue
                key, value = token.split(":", 1)
                key, value = key.casefold(), value.strip()
                if key == "place":
                    if value not in TABLE_PLACEMENTS:
                        state.warn(f"unknown table placement '{value}'")
                    else:
                        options["placement"] = value
                elif key == "span":
                    if value not in {"column", "both"}:
                        state.warn(f"unknown table span '{value}'")
                    else:
                        options["span"] = value
                elif key == "width":
                    if value not in {"natural", "fit"}:
                        state.warn(f"unknown table width '{value}'")
                    else:
                        options["width"] = value
                elif key == "cols":
                    options["columns"] = value
                else:
                    state.warn(f"unknown LaTeX table directive '{key}'")
        cleaned.append(pattern.sub("", line))
    return cleaned, options


def convert_table_callout(
    lines: list[str],
    start_index: int,
    file_prefix: str,
    state: ConversionState,
    table_placement: str = "here",
) -> tuple[str, int] | None:
    first_line = lines[start_index]
    match = TABLE_CALLOUT_RE.match(first_line)

    if not match:
        return None

    kind = match.group("kind").lower()
    tag = match.group("tag")
    first_caption = match.group("caption").strip()

    inner_lines = [first_caption]

    i = start_index + 1

    while i < len(lines) and lines[i].startswith(">"):
        inner_lines.append(strip_blockquote_marker(lines[i]))
        i += 1

    table_start = None

    for j in range(len(inner_lines) - 1):
        if (
            split_markdown_table_row(inner_lines[j]) is not None
            and is_markdown_table_separator(inner_lines[j + 1])
        ):
            table_start = j
            break

    if table_start is None:
        state.warn(f"table callout at line {start_index + 1} has no Markdown table")
        return None

    parsed = parse_table_rows_from_lines(inner_lines, table_start)

    if parsed is None:
        state.warn(f"table callout at line {start_index + 1} has malformed table")
        return None

    header, separator, rows, _ = parsed

    caption_lines, float_options = parse_table_float_options(inner_lines[:table_start], state, table_placement)
    caption_text = " ".join(
        line.strip()
        for line in caption_lines
        if line.strip()
    )

    caption_text = remove_visible_table_number(caption_text)
    if not caption_text:
        state.warn(f"table callout at line {start_index + 1} has no caption text")
        caption = None
    else:
        caption = format_caption(caption_text)

    if tag:
        label = make_prefixed_label("tab", tag, file_prefix)
    elif caption:
        label = make_prefixed_label("tab", slugify_label(caption.label_source), file_prefix)
    else:
        label = None

    long_table = kind in {"long-table", "longtable"}

    latex = convert_table_block(
        header=header,
        separator=separator,
        rows=rows,
        state=state,
        caption=caption,
        label=label,
        long_table=long_table,
        **float_options,
    )

    return latex, i


def convert_tables(text: str, file_prefix: str, state: ConversionState, table_placement: str = "here") -> str:
    lines = text.splitlines()
    out: list[str] = []

    i = 0

    while i < len(lines):
        table_callout = convert_table_callout(lines, i, file_prefix, state, table_placement)

        if table_callout is not None:
            latex, next_i = table_callout
            out.append(latex)
            i = next_i
            continue

        if (
            i + 1 < len(lines)
            and split_markdown_table_row(lines[i]) is not None
            and is_markdown_table_separator(lines[i + 1])
        ):
            state.warn(
                f"Markdown table at line {i + 1} has no [!table] or [!long-table] callout caption"
            )

            parsed = parse_table_rows_from_lines(lines, i)

            if parsed is None:
                out.append(lines[i])
                i += 1
                continue

            header, separator, rows, next_i = parsed

            out.append(
                convert_table_block(
                    header=header,
                    separator=separator,
                    rows=rows,
                    state=state,
                    caption=None,
                    label=None,
                    long_table=False,
                    placement=table_placement,
                )
            )

            i = next_i
            continue

        out.append(lines[i])
        i += 1

    return "\n".join(out)


def lookup_note(note: str, note_index: dict[str, NoteInfo], state: ConversionState) -> NoteInfo | None:
    note = normalize_note_reference(note)

    if note in note_index:
        return note_index[note]

    def canonical(name: str) -> str:
        return re.sub(r"[\s_]+", " ", name).strip().casefold()
    matches = [info for name, info in note_index.items() if canonical(name) == canonical(note)]
    if len(matches) == 1:
        return matches[0]
    if len(matches) > 1:
        state.warn(f"ambiguous external note '{note}' matches multiple filenames")
        return None

    state.warn(f"unknown external note '{note}' in wikilink")
    return None


def convert_wikilinks(
    text: str,
    current_info: NoteInfo,
    note_index: dict[str, NoteInfo],
    state: ConversionState,
) -> str:
    pattern = re.compile(
        r"\[\["
        r"(?P<note>[^\]#|]*)"
        r"(?:#(?P<heading>[^\]|]+))?"
        r"(?:\|[^\]]*)?"
        r"\]\]"
    )

    # A section range can be written with two ordinary Obsidian wikilinks:
    # [[Note#Heading A|Sections 2.3.4]]–[[Note#Heading B|2.3.6]]
    # The aliases after '|' are for Obsidian only: LaTeX uses live section numbers.
    range_pattern = re.compile(
        r"(?P<start>\[\[[^\]\n]*\]\])"
        r"[ \t]*(?:--|[–—-])[ \t]*"
        r"(?P<end>\[\[[^\]\n]*\]\])"
    )

    def resolve_section_endpoint(link: str) -> str | None:
        match = pattern.fullmatch(link)
        if match is None or not match.group("heading"):
            return None
        note = match.group("note").strip()
        if note:
            # Use the same underscore/space matching as ordinary wikilinks.
            target = note_index.get(note)
            if target is None:
                normalized = re.sub(r"[\s_]+", " ", note).strip().casefold()
                matches = [info for name, info in note_index.items()
                           if re.sub(r"[\s_]+", " ", name).strip().casefold() == normalized]
                if len(matches) != 1:
                    return None  # Let ordinary wikilink conversion report the issue.
                target = matches[0]
        else:
            target = current_info
        heading = remove_heading_numbering(match.group("heading").strip())
        _, clean_heading = split_appendix_title(heading)
        ref = target.headings.get(slugify_label(clean_heading))
        if ref is None or ref[0] != "Section":
            return None
        return ref[1]

    def range_repl(match: re.Match) -> str:
        start = resolve_section_endpoint(match.group("start"))
        end = resolve_section_endpoint(match.group("end"))
        if start is None or end is None:
            return match.group(0)
        return (rf"\hyperref[{start}]{{Sections~\ref*{{{start}}}}}"
                rf"--\hyperref[{end}]{{\ref*{{{end}}}}}")

    text = range_pattern.sub(range_repl, text)

    def repl(match: re.Match) -> str:
        note = match.group("note").strip()
        heading = match.group("heading")

        if note:
            target_info = lookup_note(note, note_index, state)

            if target_info is None:
                fallback_prefix = raw_prefix_from_title(note)
                target_info = NoteInfo(
                    title=note,
                    path=Path(note + ".md"),
                    latex_type="section",
                    latex_parent=None,
                    prefix=fallback_prefix,
                    note_label="sec",
                    heading_label="subsec",
                    headings={},
                )
        else:
            target_info = current_info

        if heading:
            heading = remove_heading_numbering(heading.strip())
            is_appendix, clean_heading = split_appendix_title(heading)
            heading_slug = slugify_label(clean_heading)

            if heading_slug in target_info.headings:
                ref_word, label = target_info.headings[heading_slug]
                return latex_hyper_ref(ref_word, label)

            if note:
                state.warn(
                    f"unresolved heading '{heading}' in note '{target_info.title}'"
                )
            else:
                state.warn(
                    f"unresolved same-note heading '{heading}'"
                )

            if is_appendix:
                label = f"app:{target_info.prefix}_{heading_slug}"
                return latex_hyper_ref("Appendix", label)

            label = f"{target_info.heading_label}:{target_info.prefix}_{heading_slug}"
            return latex_hyper_ref(ref_word_from_label(label), label)

        label = f"{target_info.note_label}:{target_info.prefix}"
        return latex_hyper_ref(ref_word_from_label(label), label)

    return pattern.sub(repl, text)


def warn_if_unconverted_syntax_remains(text: str, state: ConversionState) -> None:
    if "[[" in text or "]]" in text:
        state.warn("unconverted wikilink syntax remains")

    if "![[" in text:
        state.warn("unconverted Obsidian embed syntax remains")

    if re.search(r"(?mi)^>\s*\[!(?:table|long-table|longtable)\b", text):
        state.warn("unconverted table callout remains; check [!table: TAG] syntax and table rows")

    if re.search(r"\\ref\{(?:eq|fig|tab|table):", text):
        state.warn("unconverted object reference remains (check reference syntax)")

    raw_heading = re.search(r"(?m)^#\s+", text)
    if raw_heading:
        state.warn("raw level-1 Markdown heading remains; filename should define the top-level heading")


def convert_markdown_to_latex(
    markdown: str,
    source_path: Path,
    note_index: dict[str, NoteInfo],
    state: ConversionState,
    figure_placement_mode: str = "first",
    figure_dir: str | None = None,
    table_placement_mode: str = "auto",
) -> str:
    current_info = note_index.get(source_path.stem)

    if current_info is None:
        current_info = make_note_info(source_path, markdown, state, force=True)

    if current_info is None:
        raise RuntimeError("could not construct note info for source file")

    document_level = resolve_document_level(source_path, current_info, state)
    if figure_dir is None:
        figure_dir = "Chapters/Figures"
    if table_placement_mode == "auto":
        table_placement_mode = "top" if document_level == "article" else "here"
    file_prefix = current_info.prefix
    document_title = source_path.stem.strip()

    text = markdown
    text = text.replace("\u200b", "")

    text = strip_properties(text)
    text = strip_references_section(text)
    text = relocate_figures_to_first_reference(text, figure_placement_mode, state)

    current_info.headings = build_heading_ref_map(
        text,
        file_prefix,
        document_level,
        state=state,
        source_name=source_path.name,
    )

    text = convert_plugin_cross_note_refs(text, note_index, state)
    text = convert_cross_note_equation_refs(text, note_index, state)
    text = convert_equations(text, file_prefix, state)
    text = convert_figures(text, file_prefix, state, figure_placement_mode, figure_dir)

    text = convert_figure_and_equation_refs(
        text, file_prefix, state=state,
        valid_equation_tags=current_info.equation_tags,
        valid_figure_tags=current_info.figure_tags,
        valid_table_tags=current_info.table_tags,
        note_title=current_info.title,
    )

    text = convert_wikilinks(
        text,
        current_info,
        note_index,
        state,
    )

    text = convert_tables(text, file_prefix, state, table_placement_mode)

    text = convert_bold(text)
    text = convert_markdown_citations(text)

    text = convert_headings(text, file_prefix, document_level, state)

    text = re.sub(r"\\bf(?![A-Za-z])", r"\\boldsymbol", text)
    text = convert_legacy_rm(text)
    text = re.sub(r"\\lt(?![A-Za-z])", "<", text)
    text = re.sub(r"\\gt(?![A-Za-z])", ">", text)

    text = convert_percent_signs(text)

    warn_if_unconverted_syntax_remains(text, state)

    document_title_latex = escape_latex_text(document_title)

    if document_level == "article":
        # No visible title/section wrapper: article templates own title/abstract.
        # The optional document anchor still supports links to the article note.
        label = f"doc:{file_prefix}"
        state.register_label(label, "article body")
        return rf"\phantomsection\label{{{label}}}" + "\n\n" + f"{text.strip()}\n"

    if document_level == "chapter":
        label = f"ch:{file_prefix}"
        state.register_label(label, "document title")

        return (
            rf"\chapter{{{document_title_latex}}}" "\n"
            rf"\label{{{label}}}" "\n\n"
            f"{text.strip()}\n"
        )

    label = f"sec:{file_prefix}"
    state.register_label(label, "document title")

    return (
        rf"\section{{{document_title_latex}}}" "\n"
        rf"\label{{{label}}}" "\n\n"
        f"{text.strip()}\n"
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Convert an Obsidian Markdown thesis section, chapter or article body to LaTeX."
    )

    parser.add_argument(
        "markdown_file",
        help="Markdown file to convert.",
    )

    parser.add_argument(
        "--root",
        default=None,
        help=(
            "Project/vault root to scan for external note metadata and headings. "
            "Defaults to the source file's directory."
        ),
    )

    parser.add_argument(
        "--figure-placement",
        choices=("first", "top", "near", "section", "here"),
        default="first",
        help=("Default figure placement: first moves the image after the paragraph "
              "containing its first local reference, then floats at page top [!t]; "
              "top keeps source position and floats at page top [!t]; near permits here/top/bottom/page; "
              "section anchors at the source and adds a FloatBarrier; "
              "here anchors at the source. Individual images can override with |place:MODE. "
              "Anchored modes require the float package; section also needs placeins."),
    )

    parser.add_argument(
        "--figure-dir", default=None,
        help="LaTeX-side figure directory (default: Chapters/Figures in all document modes). No files are converted here.",
    )

    parser.add_argument(
        "--table-placement", choices=("auto", "top", "near", "section", "here"), default="auto",
        help=("Table placement: auto preserves [H] for thesis and uses top for Article. "
              "Override per callout with an invisible <!-- latex: place:top span:both width:fit cols:lXrr --> comment. "
              r"width:fit requires \usepackage{tabularx}; section requires \usepackage{placeins}."),
    )

    parser.add_argument(
        "--strict", action="store_true",
        help="Do not emit LaTeX when conversion warnings occur (exit status 2).",
    )

    parser.add_argument(
        "--no-warnings",
        action="store_true",
        help="Disable warnings to stderr.",
    )

    return parser.parse_args()


def main() -> None:
    args = parse_args()

    source_path = Path(args.markdown_file).expanduser().resolve()

    if source_path.suffix.lower() != ".md":
        raise SystemExit(f"Not a Markdown file: {source_path}")

    if args.root:
        root = Path(args.root).expanduser().resolve()
    else:
        root = source_path.parent

    if not root.exists():
        raise SystemExit(f"Root path does not exist: {root}")

    state = ConversionState(warnings_enabled=args.strict or not args.no_warnings)

    markdown = source_path.read_text(encoding="utf-8")

    note_index = build_project_index(root, source_path, state)

    latex = convert_markdown_to_latex(
        markdown=markdown,
        source_path=source_path,
        note_index=note_index,
        state=state,
        figure_placement_mode=args.figure_placement,
        figure_dir=args.figure_dir,
        table_placement_mode=args.table_placement,
    )

    if args.strict and state.warning_count:
        print(f"ERROR: conversion stopped: {state.warning_count} warning(s) in strict mode", file=sys.stderr)
        raise SystemExit(2)
    print(latex)


if __name__ == "__main__":
    main()
